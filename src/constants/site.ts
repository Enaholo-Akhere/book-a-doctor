import type { Metadata } from 'next';

/** Public origin of the site, used for canonical URLs, the sitemap and social previews. */
export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL || 'https://care-connect-ena.netlify.app').replace(/\/$/, '');

export const SITE_NAME = 'CareConnect';

export const SITE_DESCRIPTION =
  'Book online consultations with licensed doctors and specialists. Video, voice and secure chat appointments from the comfort of your home.';

/** Backend origin for server-side fetches (inlined by next.config.ts). */
export const BACKEND_ORIGIN = process.env.NEXT_PUBLIC_BACKEND_ORIGIN || 'https://doctor-webapp-backend-zxn3.onrender.com';

/** The default social preview image generated by app/opengraph-image.tsx. */
const DEFAULT_OG_IMAGE = {
  url: '/opengraph-image',
  width: 1200,
  height: 630,
  alt: `${SITE_NAME} – Online consultations with licensed doctors`,
};

/** For pages that must stay out of search results (auth, dashboards, payments). */
export const NO_INDEX: Metadata['robots'] = { index: false, follow: true };

/**
 * Metadata for a public, indexable page: title, description, canonical URL
 * and matching Open Graph / Twitter tags. The social image comes from
 * app/opengraph-image.tsx.
 */
export const pageMetadata = ({
  title,
  description,
  path,
  absoluteTitle = false,
}: {
  title: string;
  description: string;
  path: string;
  /** Use `title` as-is instead of appending " | CareConnect". */
  absoluteTitle?: boolean;
}): Metadata => {
  const fullTitle = absoluteTitle ? title : `${title} | ${SITE_NAME}`;
  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: 'website',
      siteName: SITE_NAME,
      locale: 'en_US',
      url: path,
      title: fullTitle,
      description,
      // A page-level openGraph object replaces the inherited one, image
      // included, so point back at app/opengraph-image.tsx explicitly.
      images: [DEFAULT_OG_IMAGE],
    },
    twitter: {
      card: 'summary_large_image',
      title: fullTitle,
      description,
      images: [DEFAULT_OG_IMAGE.url],
    },
  };
};
